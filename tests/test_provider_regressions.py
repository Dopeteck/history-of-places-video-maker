def outline_payload(accessory, *, include_id=True, name="Mansa Musa"):
    cast = {
        "name": name,
        "role": "ruler",
        "trait": "ambitious",
        "accessory": accessory,
        "accent": ACCENT,
    }
    if include_id:
        cast["id"] = "mansa_musa"
    return {
        "title": "The Mali Empire",
        "hook": "A journey changed a kingdom's reputation.",
        "logline": "The ruler of Mali travels across continents.",
        "cast": [cast],
        "chapters": [{
            "title": "The journey",
            "purpose": "Explain the journey",
            "key_events": ["He travelled"],
        }],
        "ending": "The journey became a story told far beyond Mali.",
    }


def chapter_payload(*, props, x, include_actor_id=False):
    actor = {"x": x, "pose": "standing", "expression": "neutral", "name": "Mansa Musa"}
    if include_actor_id:
        actor["id"] = "mansa_musa"
    return {
        "summary": "Mansa Musa travels.",
        "scenes": [{
            "narration": "Mansa Musa begins the journey.",
            "characters_on_screen": [actor],
            "background": "palace",
            "camera": "static",
            "effects": ["cut"],
            "props": props,
            "source_ids": [],
            "uncertainty": "unverified",
            "emphasis_words": [],
        } for _ in range(4)],
    }


class ProviderRegressionTests(unittest.TestCase):
    def test_groq_catalogue_403_falls_through_to_chat(self):
        provider = {
            "name": "groq", "type": "openai", "env_key": "GROQ_API_KEY",
            "models": ["openai/gpt-oss-120b", "openai/gpt-oss-20b"],
            "verify_models": True, "base_url": "https://api.groq.com/openai/v1",
        }
        chat_call = Mock(return_value='{"ok": true}')
        client = JsonLLM(call=chat_call, providers=[provider])
        with patch.dict(os.environ, {"GROQ_API_KEY": "test-key"}), \
             patch.object(llm, "_groq_models", side_effect=ProviderHTTPError(
                 403, GROQ_CLOUDFLARE_1010_BODY, "catalogue forbidden"
             )) as catalogue:
            with self.assertLogs("llm", level="WARNING") as logged:
                result = client.generate("system", {}, lambda data: data)
        self.assertTrue(any("HTTP 403" in line and "browser_signature_banned" in line
                            for line in logged.output))
        self.assertEqual(result, {"ok": True})
        chat_call.assert_called_once()
        self.assertEqual(chat_call.call_args.args[0]["type"], "openai")
        catalogue.assert_called_once()

    def test_groq_any_catalogue_error_is_advisory_and_cached_as_unavailable(self):
        provider = {
            "name": "groq", "type": "openai", "env_key": "GROQ_API_KEY",
            "models": ["model-a", "model-b"], "verify_models": True,
        }
        client = JsonLLM(providers=[provider])
        failures = [
            urllib.error.URLError("temporary DNS failure"),
            ValueError("malformed /models payload"),
        ]
        for failure in failures:
            with self.subTest(failure=type(failure).__name__):
                client = JsonLLM(providers=[provider])
                with patch.dict(os.environ, {"GROQ_API_KEY": "test-key"}), \
                     patch.object(llm, "_groq_models", side_effect=failure) as catalogue:
                    self.assertTrue(client._model_available(provider, "model-a"))
                    self.assertTrue(client._model_available(provider, "model-b"))
                    catalogue.assert_called_once()

    def test_groq_chat_uses_openai_sdk(self):
        result_response = types.SimpleNamespace(
            choices=[types.SimpleNamespace(message=types.SimpleNamespace(content='{"ok": true}'))]
        )
        calls = []
        class FakeCompletions:
            def create(self, **kwargs):
                calls.append(kwargs)
                return result_response
        fake_client = types.SimpleNamespace(
            chat=types.SimpleNamespace(completions=FakeCompletions())
        )
        class FakeOpenAI:
            def __init__(self, **kwargs):
                self.init_kwargs = kwargs
            def __enter__(self):
                return fake_client
            def __exit__(self, *args):
                return False
        openai = types.ModuleType("openai")
        openai.OpenAI = FakeOpenAI
        with patch.dict(sys.modules, {"openai": openai}), \
             patch.dict(os.environ, {"GROQ_API_KEY": "test-key"}):
            result = provider_call(
                {"type": "openai", "env_key": "GROQ_API_KEY",
                 "base_url": "https://api.groq.com/openai/v1"},
                "model-a", "system", "user",
            )
        self.assertEqual(result, '{"ok": true}')
        self.assertEqual(calls[0]["model"], "model-a")
        self.assertEqual(calls[0]["messages"][-1]["content"], "user")

    def test_gemini_uses_60000ms_timeout_and_closes_client(self):
        response = types.SimpleNamespace(text='{"ok": true}')
        http_options_seen = []
        class FakeModels:
            def generate_content(self, **kwargs):
                return response
        class FakeClient:
            def __init__(self):
                self.models = FakeModels()
                self.closed = False
            def close(self):
                self.closed = True
        client = FakeClient()
        genai = types.ModuleType("google.genai")
        genai.Client = lambda **kwargs: client
        sdk_types = types.ModuleType("google.genai.types")
        sdk_types.HttpOptions = lambda **kwargs: http_options_seen.append(kwargs) or types.SimpleNamespace(**kwargs)
        sdk_types.GenerateContentConfig = lambda **kwargs: types.SimpleNamespace(**kwargs)
        google = types.ModuleType("google")
        google.genai = genai
        with patch.dict(sys.modules, {
            "google": google, "google.genai": genai, "google.genai.types": sdk_types,
        }), patch.dict(os.environ, {"GEMINI_API_KEY": "test-key"}):
            result = provider_call(
                {"type": "gemini", "env_key": "GEMINI_API_KEY"},
                "test-model", "system", "user",
            )
        self.assertEqual(result, '{"ok": true}')
        self.assertEqual(http_options_seen, [{"timeout": 60000}])
        self.assertTrue(client.closed)


class StoryPayloadNormalisationTests(unittest.TestCase):
    def test_prior_list_accessory_payload_is_repaired_and_missing_cast_id_generated(self):
        # Regression for the previously observed accessory=["crown"] payload.
        payload = outline_payload(["crown"], include_id=False)
        result = validate_outline(payload, 1)
        self.assertEqual(result["cast"][0]["id"], "mansa_musa")
        self.assertEqual(result["cast"][0]["accessory"], "crown")

    def test_accessory_synonyms_case_spaces_and_unknown_fallback(self):
        cases = [
            ("Headscarf", "headwrap"),
            ("scarf", "headwrap"),
            ("turban", "headwrap"),
            ("tie", "bow_tie"),
            ("BowTie", "bow_tie"),
            ("Bow Tie", "bow_tie"),
            ("helmet", "hat"),
            ("Cap", "hat"),
            ("spectacles", "glasses"),
            ("staff", "spear"),
            ("Not An Accessory", "none"),
            (["crown"], "crown"),
        ]
        for raw, expected in cases:
            with self.subTest(raw=raw):
                result = validate_outline(outline_payload(raw), 1)
                self.assertEqual(result["cast"][0]["accessory"], expected)

    def test_chapter_repairs_invalid_props_missing_actor_id_and_clamps_x(self):
        payload = chapter_payload(
            props=["Staff", "coin purse", "dragon", "staff"], x=1.7,
        )
        result = validate_chapter(
            payload, {"mansa_musa": "Mansa Musa"}, set(), 1, 1, 5000,
        )
        self.assertEqual(result["scenes"][0]["props"], ["spear"])
        self.assertEqual(result["scenes"][0]["characters_on_screen"][0]["id"], "mansa_musa")
        self.assertEqual(result["scenes"][0]["characters_on_screen"][0]["x"], 0.9)

    def test_chapter_clamps_low_x_and_defaults_non_numeric_x(self):
        low = chapter_payload(props=["unknown"], x=-5)
        result = validate_chapter(low, {"mansa_musa": "Mansa Musa"}, set(), 1, 1, 5000)
        self.assertEqual(result["scenes"][0]["characters_on_screen"][0]["x"], 0.1)
        invalid = chapter_payload(props=None, x="not-a-number")
        result = validate_chapter(invalid, {"mansa_musa": "Mansa Musa"}, set(), 1, 1, 5000)
        self.assertEqual(result["scenes"][0]["characters_on_screen"][0]["x"], 0.5)
        self.assertEqual(result["scenes"][0]["props"], [])

    def test_missing_and_duplicate_cast_ids_are_repaired_deterministically(self):
        payload = outline_payload("crown", include_id=False)
        payload["cast"].append({
            "name": "Mansa Musa", "role": "ruler", "trait": "ambitious",
            "accessory": "unknown", "accent": ACCENT,
        })
        result = validate_outline(payload, 1)
        self.assertEqual([c["id"] for c in result["cast"]], ["mansa_musa", "mansa_musa_2"])
        self.assertEqual(result["cast"][1]["accessory"], "none")


